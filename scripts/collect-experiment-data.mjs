function collectTechnologyMetrics(technology) {
  const sourcePath = path.join(rootDir, technology.sourceDir);
  const packagePath = technology.packageJson ? path.join(rootDir, technology.packageJson) : null;
  const buildPath = technology.buildDir ? path.join(rootDir, technology.buildDir) : null;
  const sourceFiles = existsSync(sourcePath) ? listFiles(sourcePath).filter(isSourceFile) : [];

  return {
    id: technology.id,
    name: technology.name,
    sourceDir: technology.sourceDir,
    files: sourceFiles.length,
    loc: sourceFiles.reduce((sum, file) => sum + countLines(file), 0),
    dependencies: packagePath && existsSync(packagePath) ? countDependencies(packagePath) : 0,
    buildKb: buildPath && existsSync(buildPath) ? Math.round(getDirectorySize(buildPath) / 1024) : null
  };
}

function readHypotheses() {
  const filePath = path.join(rootDir, 'apps/main-app/src/data/hypotheses.ts');
  if (!existsSync(filePath)) {
    return [];
  }

  const source = readFileSync(filePath, 'utf8');
  const records = [];
  const blocks = source.match(/\{\n\s+id: 'H\d'[\s\S]*?\n\s+\}/g) ?? [];

  for (const block of blocks) {
    const id = matchString(block, /id: '(H\d)'/);
    const title = matchString(block, /title: '([^']+)'/);
    const statement = matchMultilineString(block, /statement:\s*([\s\S]*?),\n\s+relatedCriteria:/);
    const relatedCriteria = matchArray(block, /relatedCriteria: \[([^\]]+)\]/);
    const relatedMetrics = matchArray(block, /relatedMetrics: \[([^\]]+)\]/);
    const componentIds = matchArray(block, /componentIds: \[([^\]]+)\]/);
    const technologyIds = matchArray(block, /technologyIds: \[([^\]]+)\]/);

    if (id) {
      records.push({ id, title, statement, relatedCriteria, relatedMetrics, componentIds, technologyIds });
    }
  }

  return records;
}

function listFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? listFiles(fullPath) : [fullPath];
  });
}

function isSourceFile(filePath) {
  return /\.(ts|tsx|js|jsx|vue|css|html)$/.test(filePath);
}

function countLines(filePath) {
  const content = readFileSync(filePath, 'utf8').trim();
  return content ? content.split(/\r?\n/).length : 0;
}

function countDependencies(packagePath) {
  const packageJson = JSON.parse(readFileSync(packagePath, 'utf8'));
  return Object.keys(packageJson.dependencies ?? {}).length;
}

function getDirectorySize(directory) {
  return listFiles(directory).reduce((sum, file) => sum + statSync(file).size, 0);
}

function matchString(source, regex) {
  return source.match(regex)?.[1] ?? '';
}

function matchMultilineString(source, regex) {
  const raw = source.match(regex)?.[1] ?? '';
  return raw
    .split('\n')
    .map((line) => line.trim())
    .join(' ')
    .replace(/^'/, '')
    .replace(/'$/, '')
    .replaceAll("' + '", '')
    .trim();
}

function matchArray(source, regex) {
  const raw = source.match(regex)?.[1] ?? '';
  return raw
    .split(',')
    .map((item) => item.trim().replaceAll("'", ''))
    .filter(Boolean);
}

function toCsv(rows) {
  const header = ['id', 'name', 'sourceDir', 'files', 'loc', 'dependencies', 'buildKb'];
  return [header.join(','), ...rows.map((row) => header.map((key) => csvCell(row[key])).join(','))].join('\n') + '\n';
}

function hypothesesToCsv(rows) {
  const header = ['id', 'title', 'relatedCriteria', 'relatedMetrics', 'componentIds', 'technologyIds'];
  return [header.join(','), ...rows.map((row) => header.map((key) => csvCell(Array.isArray(row[key]) ? row[key].join('|') : row[key])).join(','))].join('\n') + '\n';
}

function csvCell(value) {
  if (value === null || value === undefined) {
    return '';
  }

  const text = String(value);
  return /[",\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}
